-- 03_create_dimensions.sql
-- Dimensões do Data Mart (surrogate keys geradas pelo PostgreSQL).
--
--   psql -h localhost -U postgres -d dm_anp_pernambuco -f sql/03_create_dimensions.sql
-- =============================================================================

-- -----------------------------------------------------------------------------
-- dim_tempo: granularidade SEMESTRAL. Um registro por semestre do período do
-- Data Mart (2020.1 a 2026.1).
-- id_tempo = ano * 10 + semestre (ex.: 20241 = 1º semestre de 2024): surrogate
-- key inteira, estável e legível.
-- A data exata de cada coleta fica na própria fato (data_coleta).
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dim_tempo (
    id_tempo       INTEGER      PRIMARY KEY,
    ano            SMALLINT     NOT NULL,
    semestre       SMALLINT     NOT NULL,   -- 1 = jan-jun, 2 = jul-dez
    nome_semestre  VARCHAR(15)  NOT NULL,   -- ex.: 1º semestre
    periodo        VARCHAR(6)   NOT NULL,   -- ex.: 2024.1
    CONSTRAINT uq_dim_tempo_ano_semestre UNIQUE (ano, semestre),
    CONSTRAINT uq_dim_tempo_periodo      UNIQUE (periodo),
    CONSTRAINT ck_dim_tempo_semestre     CHECK (semestre IN (1, 2))
);

-- -----------------------------------------------------------------------------
-- dim_combustivel: origem PRODUTO e UNIDADE DE MEDIDA (categoria derivada do produto).
-- Chave natural: combustivel (= coluna Produto da ANP).
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dim_combustivel (
    id_combustivel  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    combustivel     VARCHAR(60)  NOT NULL,
    categoria       VARCHAR(60),
    unidade_medida  VARCHAR(20),
    CONSTRAINT uq_dim_combustivel UNIQUE (combustivel)
);

-- -----------------------------------------------------------------------------
-- dim_local: o posto revendedor E onde ele fica.
-- Junta o cadastro da revenda (CNPJ, nome, endereço) com a localização
-- geográfica (município, UF, estado, região), para que cada posto já traga
-- de qual município/estado/região ele é.
-- Chave natural: cnpj. SCD tipo 1 (guarda o cadastro mais recente do posto).
-- Origem (CSV da ANP): CNPJ da Revenda, Revenda, Nome da Rua, Numero Rua,
-- Complemento, Bairro, Cep, Municipio, Estado - Sigla, Regiao - Sigla;
-- estado (nome) é derivado da UF.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dim_local (
    id_local      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- posto revendedor
    cnpj          VARCHAR(18)  NOT NULL,   -- CNPJ do posto (chave natural)
    nome_revenda  VARCHAR(200),            -- razão social do posto
    -- endereço do posto
    rua           VARCHAR(200),
    numero        VARCHAR(30),
    complemento   VARCHAR(200),
    bairro        VARCHAR(100),
    cep           VARCHAR(9),
    -- localização geográfica (hierarquia: região > estado > município)
    municipio     VARCHAR(100) NOT NULL,
    uf            CHAR(2)      NOT NULL,   -- sigla do estado (ex.: PE)
    estado        VARCHAR(50),             -- nome do estado (ex.: Pernambuco)
    regiao        VARCHAR(5),              -- sigla da região (ex.: NE)
    CONSTRAINT uq_dim_local_cnpj UNIQUE (cnpj)
);

COMMENT ON TABLE  dim_local           IS 'Posto revendedor e sua localização (endereço, município, UF, estado, região)';
COMMENT ON COLUMN dim_local.cnpj      IS 'CNPJ do posto revendedor (chave natural)';
COMMENT ON COLUMN dim_local.municipio IS 'Município onde o posto fica';
COMMENT ON COLUMN dim_local.uf        IS 'Sigla do estado onde o posto fica';

-- -----------------------------------------------------------------------------
-- dim_bandeira: origem BANDEIRA. Fica fora da dim_local porque o mesmo
-- posto troca de bandeira ao longo do tempo.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dim_bandeira (
    id_bandeira  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bandeira     VARCHAR(100) NOT NULL,
    CONSTRAINT uq_dim_bandeira UNIQUE (bandeira)
);
